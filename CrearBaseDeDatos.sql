-- PROCEDIMIENTO 2: Insertar MODULO

CREATE PROCEDURE PA_INSERTAR_MODULO
    @NOMBRE_CICLO NVARCHAR(30),
    @NOMBRE_MODULO NVARCHAR(100)
AS
    DECLARE @ID_CICLO SMALLINT
    SELECT @ID_CICLO = ID_CICLO
    FROM CICLOS
    WHERE NOMBRECICLO = @NOMBRE_CICLO

    IF @ID_CICLO IS NULL
        PRINT 'No existe este ciclo'
    ELSE
    BEGIN
        DECLARE @NUEVO_ID SMALLINT
        SELECT @NUEVO_ID = ISNULL(MAX(ID_MODULO),0) + 1
        FROM MODULOS
        WHERE ID_CICLO = @ID_CICLO

        INSERT INTO MODULOS (ID_CICLO, ID_MODULO, MODULO)
        VALUES (@ID_CICLO, @NUEVO_ID, @NOMBRE_MODULO)
    END
-- LLAMADA
PA_INSERTAR_MODULO 'DESARROLLO DE APLICACIONES WEB', 'BASES DE DATOS'
PA_INSERTAR_MODULO 'DESARROLLO DE APLICACIONES WEB', 'PROGRAMACIÓN'



-- PROCEDIMIENTO 3: Insertar RA

CREATE PROCEDURE PA_INSERTAR_RA
    @NOMBRE_CICLO NVARCHAR(30),
    @NOMBRE_MODULO NVARCHAR(100),
    @TEXTO_RA NVARCHAR(100)
AS
    DECLARE @ID_CICLO SMALLINT
    SELECT @ID_CICLO = ID_CICLO
    FROM CICLOS
    WHERE NOMBRECICLO = @NOMBRE_CICLO

    IF @ID_CICLO IS NULL
    BEGIN
        PRINT 'No existe este ciclo'
        RETURN
    END

    DECLARE @ID_MODULO SMALLINT
    SELECT @ID_MODULO = ID_MODULO
    FROM MODULOS
    WHERE ID_CICLO = @ID_CICLO AND MODULO = @NOMBRE_MODULO

    IF @ID_MODULO IS NULL
        PRINT 'No existe este modulo en el ciclo puesto'
    ELSE
    BEGIN
        DECLARE @NUEVO_ID SMALLINT
        SELECT @NUEVO_ID = ISNULL(MAX(ID_RA), 0) + 1
        FROM RA
        WHERE ID_CICLO = @ID_CICLO AND ID_MODULO = @ID_MODULO

        INSERT INTO RA (ID_CICLO, ID_MODULO, ID_RA, RA)
        VALUES (@ID_CICLO, @ID_MODULO, @NUEVO_ID, @TEXTO_RA)
    END
-- LLAMADA
PA_INSERTAR_RA 'DESARROLLO DE APLICACIONES WEB', 'BASES DE DATOS', 'Crea bases de datos definiendo su estructura'
PA_INSERTAR_RA 'DESARROLLO DE APLICACIONES WEB', 'BASES DE DATOS', 'Realiza consultas sobre una o varias tablas'



-- PROCEDIMIENTO 4: Insertar JORNADA

CREATE PROCEDURE PA_INSERTAR_JORNADA
    @DNI CHAR(9),
    @HORAS FLOAT = 8,
    @FECHA_ENTRADA DATETIME,
    @ESTADO NVARCHAR(30)
AS
    IF NOT EXISTS (SELECT * FROM ALUMNOS WHERE DNI = @DNI)
        PRINT 'No hay alumnos con este dni'
    ELSE
    BEGIN
        DECLARE @NUEVO_ID SMALLINT
        SELECT @NUEVO_ID = ISNULL(MAX(ID_JORNADA), 0) + 1
        FROM JORNADAS
        WHERE DNI = @DNI

        INSERT INTO JORNADAS (DNI, ID_JORNADA, HORAS, FECHA_ENTRADA, ESTADO)
        VALUES (@DNI, @NUEVO_ID, @HORAS, @FECHA_ENTRADA, @ESTADO)
    END
-- LLAMADA
