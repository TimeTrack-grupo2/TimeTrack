PA_INSERTAR_JORNADA '12345678A', 5, '2024-01-16', 'EN CURSO'



-- PROCEDIMIENTO 5: Insertar TAREA

CREATE PROCEDURE PA_INSERTAR_TAREA
    @DNI CHAR(9),
    @ID_JORNADA SMALLINT,
    @HORAS FLOAT,
    @DESCRIPCION NVARCHAR(150)
AS
    IF NOT EXISTS (SELECT * FROM JORNADAS WHERE DNI = @DNI AND ID_JORNADA = @ID_JORNADA)
        PRINT 'No existe esa jornada para el alumno puesto'
    ELSE
    BEGIN
        DECLARE @NUEVO_ID SMALLINT
        SELECT @NUEVO_ID = ISNULL(MAX(ID_TAREA), 0) + 1
        FROM TAREAS
        WHERE DNI = @DNI AND ID_JORNADA = @ID_JORNADA

        INSERT INTO TAREAS (DNI, ID_JORNADA, ID_TAREA, HORAS, DESCRIPCION)
        VALUES (@DNI, @ID_JORNADA, @NUEVO_ID, @HORAS, @DESCRIPCION)
    END
