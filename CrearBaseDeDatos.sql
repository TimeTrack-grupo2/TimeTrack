-- PROCEDIMIENTO 1: Insertar CICLO

CREATE PROCEDURE PA_INSERTAR_CICLO
    @NOMBRE NVARCHAR(30)
AS
    IF EXISTS (SELECT ID_CICLO FROM CICLOS WHERE NOMBRECICLO = @NOMBRE)
        PRINT 'Ya existe un ciclo con este nombre'
    ELSE
    BEGIN
        DECLARE @NUEVO_ID SMALLINT
        SELECT @NUEVO_ID = ISNULL(MAX(ID_CICLO), 0) + 1
        FROM CICLOS

        INSERT INTO CICLOS (ID_CICLO, NOMBRECICLO)
        VALUES (@NUEVO_ID, @NOMBRE)
    END
