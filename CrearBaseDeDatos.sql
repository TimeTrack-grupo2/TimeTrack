-- PROCEDIMIENTO 6: Horas totales trabajadas

CREATE PROCEDURE sp_horas_trabajadas
    @NOMBRE    NVARCHAR(20),
    @APELLIDO1 NVARCHAR(40),
    @APELLIDO2 NVARCHAR(40)
AS
    RETURN (
        SELECT SUM(JORNADAS.HORAS)
        FROM   ALUMNOS
               INNER JOIN JORNADAS JORNADAS ON ALUMNOS.DNI = JORNADAS.DNI
        WHERE  ALUMNOS.NOMBRE    = @NOMBRE
          AND  ALUMNOS.APELLIDO1 = @APELLIDO1
          AND  ALUMNOS.APELLIDO2 = @APELLIDO2

        GROUP BY ALUMNOS.NOMBRE, ALUMNOS.APELLIDO1, ALUMNOS.APELLIDO2
        HAVING ALUMNOS.NOMBRE    = @NOMBRE
           AND ALUMNOS.APELLIDO1 = @APELLIDO1
           AND ALUMNOS.APELLIDO2 = @APELLIDO2
    )

-- LLAMADA
DECLARE @HORAS SMALLINT
EXEC @HORAS = sp_horas_trabajadas 'MAXIM', 'PASCAL', 'PASCAL2'
